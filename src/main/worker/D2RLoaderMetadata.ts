import path from 'path';
import { tl } from '../../shared/i18n';
import {
  readWindowsFileVersion,
  type D2RLoaderVersionReader,
} from './D2RLoaderInstaller';
import type { InstallationRuntime } from './InstallationRuntime';

export const D2R_LOADER_METADATA_PATH = path.join(
  '..',
  '..',
  'd2rloader',
  'metadata.json',
);

const METADATA_OPERATION = 'D2RLoader metadata';

type D2RLoaderMetadataRuntime = Pick<
  InstallationRuntime,
  'console' | 'fileManager' | 'options' | 'modsInstalled' | 'modsToInstall'
>;

export type D2RLoaderMetadataDetails = {
  author?: string;
  description?: string;
};

export function createD2RLoaderMetadata(
  version: string,
  details: D2RLoaderMetadataDetails = {},
): Buffer {
  const metadata = [
    '{',
    '  "schemaVersion": 1,',
    '  "metadata": {',
    '    "modVersion": "",',
    `    "author": ${JSON.stringify(details.author ?? '')},`,
    `    "description": ${JSON.stringify(details.description ?? '')},`,
    '    "website": ""',
    '  },',
    '  "d2rloader": {',
    `    "version": ${JSON.stringify(version)}`,
    '  }',
    '}',
    '',
  ].join('\r\n');
  return Buffer.from(metadata, 'utf8');
}

const MAX_DESCRIPTION_LENGTH = 1000;

// "Generated by D2RMM from: A, B, C" - which mods the output was built from,
// shown wherever D2RLoader displays the mod's metadata.
export function describeInstalledMods(
  runtime: Pick<InstallationRuntime, 'modsInstalled' | 'modsToInstall'>,
): string {
  const names = runtime.modsInstalled.map((id) => {
    const mod = runtime.modsToInstall.find((m) => m.id === id);
    return mod?.info?.name ?? id;
  });
  const text = `Generated by D2RMM from ${names.length} mod(s): ${names.join(', ')}`;
  return text.length > MAX_DESCRIPTION_LENGTH
    ? `${text.slice(0, MAX_DESCRIPTION_LENGTH - 3)}...`
    : text;
}

// A namespace turns every plain string record of a mod into "<namespace>:key"
// and leaves the game's own text as it was (D2RLoader wiki, String
// namespaces). D2RMM's output is many mods editing the game's string files,
// so a namespace brought in by one mod would undo the text changes of all of
// them: take it out again.
function removeNamespace(runtime: D2RLoaderMetadataRuntime): boolean {
  const data = runtime.fileManager.getData(D2R_LOADER_METADATA_PATH);
  if (data == null) {
    return false;
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(data.toString('utf8').replace(/^\uFEFF/, ''));
  } catch {
    return false;
  }
  if (
    parsed == null ||
    typeof parsed !== 'object' ||
    Array.isArray(parsed) ||
    !('namespace' in parsed)
  ) {
    return false;
  }
  const { namespace, ...rest } = parsed as Record<string, unknown>;
  runtime.console.warn(
    tl('worker.d2rloader.metadata.namespaceRemoved', {
      namespace: String(namespace),
      mods: runtime.fileManager.writers(D2R_LOADER_METADATA_PATH).join(', '),
    }),
  );
  runtime.fileManager.setData(
    D2R_LOADER_METADATA_PATH,
    Buffer.from(
      `${JSON.stringify(rest, null, 2).replace(/\n/g, '\r\n')}\r\n`,
      'utf8',
    ),
  );
  return true;
}

export async function ensureD2RLoaderMetadata(
  runtime: D2RLoaderMetadataRuntime,
  readVersion: D2RLoaderVersionReader = readWindowsFileVersion,
): Promise<boolean> {
  if (runtime.options.useD2RLoader !== true || runtime.options.isDryRun) {
    return false;
  }

  if (runtime.fileManager.exists(D2R_LOADER_METADATA_PATH)) {
    return removeNamespace(runtime);
  }

  const executablePath = path.resolve(
    runtime.options.gamePath,
    'D2RLoader.exe',
  );
  const version = readVersion(executablePath);
  if (version == null) {
    runtime.console.warn(
      `Could not read the file version from "${executablePath}" while generating d2rloader/metadata.json.`,
    );
    return false;
  }

  await runtime.fileManager.read(D2R_LOADER_METADATA_PATH, METADATA_OPERATION);
  runtime.fileManager.setData(
    D2R_LOADER_METADATA_PATH,
    createD2RLoaderMetadata(version, {
      author: 'D2RMM',
      description: describeInstalledMods(runtime),
    }),
  );
  await runtime.fileManager.write(D2R_LOADER_METADATA_PATH, METADATA_OPERATION);
  return true;
}
